// exprforge/emitters/c.js
const Emitter = require("./base.js");

function fn1(name) {
    return ([x]) => `${name}(${x})`;
}

function fn2(name) {
    return ([a, b]) => `${name}(${a}, ${b})`;
}

const emitter = new Emitter({
    ext: "c",
    // Appending ".0" unconditionally to an integer-valued number is wrong
    // once JS's own String() renders it in exponential form (>= 1e21, or
    // Number.isInteger's own "whole number" sense includes huge integer-
    // valued doubles well past that) -- "1e+250.0" is a real C syntax
    // error ("invalid suffix '.0' on floating constant"), confirmed
    // against a real gcc compile, not assumed. A string already
    // containing an exponent marker is already an unambiguous C floating
    // constant on its own (no decimal point required once there's an
    // exponent) -- ".0" is only needed to stop an otherwise-plain integer
    // literal (e.g. "5") from being read as `int` instead of `double`.
    formatNumber: (v) => {
        const s = String(v);
        if (/e/i.test(s)) return s;
        return Number.isInteger(v) ? `${s}.0` : s;
    },
    calls: {
        sqrt: fn1("sqrt"), abs: fn1("fabs"), sin: fn1("sin"), cos: fn1("cos"), tan: fn1("tan"),
        asin: fn1("asin"), acos: fn1("acos"), atan: fn1("atan"), log: fn1("log"),
        log2: fn1("log2"), log10: fn1("log10"), exp: fn1("exp"), floor: fn1("floor"),
        ceil: fn1("ceil"), round: fn1("round"), trunc: fn1("trunc"),
        pow: fn2("pow"), atan2: fn2("atan2"), min: fn2("fmin"), max: fn2("fmax"), hypot: fn2("hypot"),
        // No standard libm "sign" function — emit the comparison directly.
        sign: ([x]) => `((${x}) > 0.0 ? 1.0 : ((${x}) < 0.0 ? -1.0 : 0.0))`,
        // C's `%` is integer-only -- fmod (already available via
        // math.h) is the float-capable equivalent, sign-of-dividend like
        // C's integer %, so the double-application wrap still applies.
        wrapIndex: ([i, m]) => `(fmod(fmod(${i}, ${m}) + (${m}), ${m}))`,
        clampIndex: ([i, lo, hi]) => `fmax(${lo}, fmin(${hi}, ${i}))`,
    },
    // C array subscripts require integer type -- no implicit double
    // conversion.
    emitIndex: function (targetNode, atNode) {
        return `${this.emitExpr(targetNode)}[(int)(${this.emitExpr(atNode)})]`;
    },
    formatFunction: (fn, body, letBindings = []) => {
        const params = fn.params.map((p) => `double ${p}${fn.paramTypes?.[p] === "number[]" ? "[]" : ""}`).join(", ");
        const lets = letBindings.map(({ name, valueStr }) => `    double ${name} = ${valueStr};`).join("\n");
        const letsBlock = lets ? lets + "\n" : "";
        return `/* AUTO-GENERATED by ExprForge -- do not hand-edit. */\n` +
               `#include <math.h>\n\n` +
               `double ${fn.name}(${params})\n` +
               `{\n` +
               letsBlock +
               `    return ${body};\n` +
               `}\n`;
    },
    // Multiple named outputs from one call: C has no native multi-return,
    // so this emits a small out-struct alongside the function and returns
    // it by value (a C99 designated-initializer compound literal) — named
    // field access at the call site, not a positional tuple that's easy to
    // mix up.
    formatSuite: (fn, outputStrs, letBindings = []) => {
        const params = fn.params.map((p) => `double ${p}${fn.paramTypes?.[p] === "number[]" ? "[]" : ""}`).join(", ");
        const lets = letBindings.map(({ name, valueStr }) => `    double ${name} = ${valueStr};`).join("\n");
        const letsBlock = lets ? lets + "\n" : "";
        const outputNames = Object.keys(outputStrs);
        const structName = `${capitalize(fn.name)}Result`;
        const structFields = outputNames.map((n) => `    double ${n};`).join("\n");
        const initFields = outputNames.map((n) => `.${n} = ${outputStrs[n]}`).join(", ");
        return `/* AUTO-GENERATED by ExprForge -- do not hand-edit. */\n` +
               `#include <math.h>\n\n` +
               `typedef struct {\n${structFields}\n} ${structName};\n\n` +
               `${structName} ${fn.name}(${params})\n` +
               `{\n` +
               letsBlock +
               `    return (${structName}){ ${initFields} };\n` +
               `}\n`;
    },
});

function capitalize(s) {
    return s.charAt(0).toUpperCase() + s.slice(1);
}

module.exports = emitter;
