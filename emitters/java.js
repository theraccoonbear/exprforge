// exprforge/emitters/java.js
const Emitter = require("./base.js");

function fn1(name) {
    return ([x]) => `Math.${name}(${x})`;
}

function fn2(name) {
    return ([a, b]) => `Math.${name}(${a}, ${b})`;
}

const emitter = new Emitter({
    ext: "java",
    header: "// AUTO-GENERATED by ExprForge -- do not hand-edit.\n",
    // One public final class per output: named after the function for a
    // standalone emit, `opts.wrapperName` (default ExprForge) holding every
    // function as a static method for emitFile.
    frame: ({ header, bodies, fns, file, opts }) => {
        const cls = file ? opts.wrapperName || "ExprForge" : capitalize(fns[0].name);
        return header +
               `public final class ${cls} {\n` +
               `    private ${cls}() {\n` +
               `    }\n\n` +
               bodies.join("\n") +
               `}\n`;
    },
    // Same real bug class as c.js's formatNumber (see its comment): once
    // JS's own String() renders an integer-valued number in exponential
    // form (huge magnitudes, e.g. 1e250), unconditionally appending ".0"
    // produces "1e+250.0" -- not valid Java (a decimal point can't
    // follow the exponent part of a Java floating-point literal; the
    // fraction has to come BEFORE it, e.g. "1.0e250"). An already-
    // exponential string is already an unambiguous Java double literal
    // on its own.
    formatNumber: (v) => {
        const s = String(v);
        if (/e/i.test(s)) return s;
        return Number.isInteger(v) ? `${s}.0` : s;
    },
    calls: {
        sqrt: fn1("sqrt"), abs: fn1("abs"), sin: fn1("sin"), cos: fn1("cos"), tan: fn1("tan"),
        asin: fn1("asin"), acos: fn1("acos"), atan: fn1("atan"), log: fn1("log"),
        log10: fn1("log10"), exp: fn1("exp"), floor: fn1("floor"), ceil: fn1("ceil"),
        signum: fn1("signum"),
        pow: ([x, y]) =>
            `((java.util.function.DoubleBinaryOperator) (ef_a, ef_b) -> (ef_a == 1.0 || (ef_a == -1.0 && Math.abs(ef_b) == Double.POSITIVE_INFINITY)) ? 1.0 : Math.pow(ef_a, ef_b)).applyAsDouble(${x}, ${y})`,
        atan2: fn2("atan2"), min: fn2("min"), max: fn2("max"), hypot: fn2("hypot"),
        // Math has no log2; Java also lacks round-to-double and trunc directly.
        log2: ([x]) => `(Math.log(${x}) / Math.log(2.0))`,
        // Math.round ties toward +Infinity, NOT this project's standardized
        // round-half-AWAY-from-zero convention -- see js.js's own comment
        // and the root README's "round() at exact .5 boundaries" section.
        // Math.signum already returns double for a double argument, so no
        // cast is needed here the way the plain Math.round path above did.
        round: ([x]) =>
            `((java.util.function.DoubleUnaryOperator) (ef_a) -> Math.signum(ef_a) * ` +
            `(Math.floor(Math.abs(ef_a)) + (Math.abs(ef_a) - Math.floor(Math.abs(ef_a)) >= 0.5 ? 1.0 : 0.0))).applyAsDouble(${x})`,
        trunc: ([x]) => `((${x}) < 0.0 ? Math.ceil(${x}) : Math.floor(${x}))`,
        sign: fn1("signum"),
        wrapIndex: ([i, m]) => `(((${i} % ${m}) + ${m}) % ${m})`,
        clampIndex: ([i, lo, hi]) => `Math.max(${lo}, Math.min(${hi}, ${i}))`,
    },
    // Java array indexing requires int, not double -- no implicit
    // narrowing conversion exists for this.
    emitIndex: function (targetNode, atNode) {
        return `${this.emitExpr(targetNode)}[(int)(${this.emitExpr(atNode)})]`;
    },
    formatFunction: (fn, body, letBindings = [], guardLines = [], opts = {}) => {
        const params = fn.params.map((p) => `${fn.paramTypes?.[p] === "number[]" ? "double[]" : "double"} ${p}`).join(", ");
        const lets = letBindings.map(({ name, valueStr }) => `        double ${name} = ${valueStr};`).join("\n");
        const letsBlock = lets ? lets + "\n" : "";
        return `    public static double ${fn.name}(${params}) {\n` +
               letsBlock +
               `        return ${body};\n` +
               `    }\n`;
    },
    // Multiple named outputs from one call: Java has no native multi-return,
    // so this nests a small immutable Result class inside the same
    // top-level class every function here already gets, keeping everything
    // in the one per-function file this project's output layout assumes.
    formatSuite: (fn, outputStrs, letBindings = [], guardLines = [], opts = {}) => {
        const params = fn.params.map((p) => `${fn.paramTypes?.[p] === "number[]" ? "double[]" : "double"} ${p}`).join(", ");
        const lets = letBindings.map(({ name, valueStr }) => `        double ${name} = ${valueStr};`).join("\n");
        const letsBlock = lets ? lets + "\n" : "";
        const outputNames = Object.keys(outputStrs);
        const fields = outputNames.map((n) => `        public final double ${n};`).join("\n");
        const ctorParams = outputNames.map((n) => `double ${n}`).join(", ");
        const ctorAssigns = outputNames.map((n) => `            this.${n} = ${n};`).join("\n");
        const newArgs = outputNames.map((n) => outputStrs[n]).join(", ");
        const resultName = emitter._fileMode ? `${capitalize(fn.name)}Result` : "Result";
        return `    public static final class ${resultName} {\n` +
               `${fields}\n\n` +
               `        ${resultName}(${ctorParams}) {\n` +
               `${ctorAssigns}\n` +
               `        }\n` +
               `    }\n\n` +
               `    public static ${resultName} ${fn.name}(${params}) {\n` +
               letsBlock +
               `        return new ${resultName}(${newArgs});\n` +
               `    }\n`;
    },
});

function capitalize(s) {
    return s.charAt(0).toUpperCase() + s.slice(1);
}

