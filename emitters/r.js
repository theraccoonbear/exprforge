// exprforge/emitters/r.js
const Emitter = require("./base.js");

function quiet(expr) {
    return `suppressWarnings(${expr})`;
}

function fn1(name) {
    return ([x]) => quiet(`${name}(${x})`);
}

const emitter = new Emitter({
    ext: "R",
    header: "# AUTO-GENERATED by ExprForge -- do not hand-edit.\n",
    // R's own numeric literal syntax accepts exponent notation ("1e-9");
    // non-finite values are spelled Inf / -Inf / NaN. A negative literal is
    // parenthesized so a following "^" cannot bind tighter than the sign.
    formatNumber: (v) => {
        if (Number.isNaN(v)) return "NaN";
        if (v === Infinity) return "Inf";
        if (v === -Infinity) return "(-Inf)";
        if (Object.is(v, -0)) return "(-0)";
        return v < 0 ? `(${String(v)})` : String(v);
    },
    calls: {
        // sqrt/log*/asin/acos/sin/cos/tan return NaN for an out-of-domain
        // argument, as docs/adr/0002 requires, but R also signals a
        // "NaNs produced" warning for each. suppressWarnings() drops the
        // warning and keeps the NaN. Guarding with `if (x >= 0)` instead is
        // not possible: an R comparison against NaN is NA, and `if (NA)`
        // is an error.
        sqrt: fn1("sqrt"), abs: ([x]) => `abs(${x})`,
        sin: fn1("sin"), cos: fn1("cos"), tan: fn1("tan"),
        asin: fn1("asin"), acos: fn1("acos"),
        atan: ([x]) => `atan(${x})`,
        atan2: ([y, x]) => `atan2(${y}, ${x})`,
        log: fn1("log"),
        log2: fn1("log2"),
        log10: fn1("log10"),
        exp: ([x]) => `exp(${x})`,
        // R's ^ ignores the sign of a zero base: (-0)^-1 is +Inf and (-0)^3
        // is +0, and (-1)^+-Inf is NaN. For -0 raised to an odd integer the
        // result is taken from |base| and negated, and (-1)^+-Inf is 1, as
        // IEEE 754 requires.
        pow: ([x, y]) =>
            `(function(a, b) if (!is.na(a) && !is.na(b) && a == 0 && 1 / a < 0 && is.finite(b) && ` +
            `b == floor(b) && b %% 2 == 1) -(abs(a) ^ b) else if (!is.na(a) && a == -1 && is.infinite(b)) 1 else a ^ b)(${x}, ${y})`,
        floor: ([x]) => `floor(${x})`,
        ceil: ([x]) => `ceiling(${x})`,
        trunc: ([x]) => `trunc(${x})`,
        // Base min()/max() return NaN when either operand is NaN, in either
        // argument order (docs/adr/0003). No NA values ever occur here.
        min: ([a, b]) => `min(${a}, ${b})`,
        max: ([a, b]) => `max(${a}, ${b})`,
        // R's round() is round-half-to-even; docs/adr/0001 standardizes on
        // ties away from zero. sign(x) * floor(abs(x) + 0.5) is the shared
        // formula.
        // The exact form: floor(|a|) plus 1 when the fractional part
        // |a| - floor(|a|) (computed without rounding) is at least 0.5.
        // abs(a) + 0.5 is inexact at 0.49999999999999994 and above 2^52.
        // The sign is read from 1 / a so -0 and (-0.5, 0) give -0.
        round: ([x]) =>
            `(function(a) if (is.na(a) || is.infinite(a)) a else { m <- abs(a); f <- floor(m); ` +
            `r <- f + (m - f >= 0.5); if (1 / a < 0) -r else r })(${x})`,
        // R's sign(-0) is +0; the zero branch returns the argument itself
        // so -0 stays -0 (as Math.sign does), and NaN/NA stay NaN.
        sign: ([x]) => `(function(a) if (is.na(a) || a != 0) sign(a) else a)(${x})`,
        // Plain sqrt(a*a + b*b) when the sum is in [1e-290, 1e300] (it
        // would otherwise overflow or underflow), else the scaled form
        // with explicit Inf/NaN handling. Inf wins over NaN, as in libm.
        hypot: ([a, b]) =>
            `(function(a, b) { a <- abs(a); b <- abs(b); s <- a * a + b * b; ` +
            `if (!is.na(s) && s < 1e300 && s > 1e-290) return(sqrt(s)); ` +
            `if (is.infinite(a) || is.infinite(b)) return(Inf); ` +
            `if (is.na(a) || is.na(b)) return(NaN); ` +
            `if (a < b) { t <- a; a <- b; b <- t }; if (a == 0) return(0); ` +
            `r <- b / a; a * sqrt(1 + r * r) })(${a}, ${b})`,
        // R's %% is floor-mod: the result takes the sign of the divisor.
        wrapIndex: ([i, m]) => `((${i}) %% (${m}))`,
        clampIndex: ([i, lo, hi]) => `max(${lo}, min(${hi}, ${i}))`,
    },
    // R vectors are 1-indexed; +1 translates this AST's 0-based convention
    // at the subscript. [[ ]] (not [ ]) so an out-of-range index is an
    // error, not a silent NA, empty result, or (for a negative index) an
    // element-dropping subset. round() absorbs floating imprecision in an
    // index that is mathematically an integer.
    emitIndex: function (targetNode, atNode) {
        return `${this.emitExpr(targetNode)}[[round(${this.emitExpr(atNode)}) + 1]]`;
    },
    // `if` is an expression in R. A comparison involving NaN is NA in R,
    // and `if (NA)` is an error, so the condition goes through isTRUE():
    // NaN compares false for > < >= <= ==, as in JS. "!=" is spelled as
    // the negation of "==" because NaN != x is true in JS but NA in R.
    emitSelect: function (condNode, thenStr, elseStr) {
        const L = this.emitExpr(condNode.left);
        const R = this.emitExpr(condNode.right);
        const test = condNode.op === "!="
            ? `!isTRUE(${L} == ${R})`
            : `isTRUE(${L} ${condNode.op} ${R})`;
        return `(if (${test}) ${thenStr} else ${elseStr})`;
    },
    typeGuard: (p, fnName) =>
        `if (!is.numeric(${p})) stop(${JSON.stringify(`${fnName}: "${p}" must be a numeric vector (array)`)})`,
    lengthGuard: (p, lenP, fnName) =>
        `if (length(${p}) != ${lenP}) stop(${JSON.stringify(`${fnName}: length("${p}") must equal "${lenP}"`)})`,
    formatFunction: (fn, body, letBindings = [], guardLines = []) => {
        const params = fn.params.join(", ");
        const guards = guardLines.map((l) => `    ${l}`).join("\n");
        const guardsBlock = guards ? guards + "\n" : "";
        const lets = letBindings.map(({ name, valueStr }) => `    ${name} <- ${valueStr}`).join("\n");
        const letsBlock = lets ? lets + "\n" : "";
        return `${fn.name} <- function(${params}) {\n` +
               guardsBlock +
               letsBlock +
               `    return(${body})\n` +
               `}\n`;
    },
    // Multiple named outputs from one call: a named list, read with
    // result$name at the call site.
    formatSuite: (fn, outputStrs, letBindings = [], guardLines = []) => {
        const params = fn.params.join(", ");
        const guards = guardLines.map((l) => `    ${l}`).join("\n");
        const guardsBlock = guards ? guards + "\n" : "";
        const lets = letBindings.map(({ name, valueStr }) => `    ${name} <- ${valueStr}`).join("\n");
        const letsBlock = lets ? lets + "\n" : "";
        const returnExpr = Object.keys(outputStrs).map((n) => `${n} = ${outputStrs[n]}`).join(", ");
        return `${fn.name} <- function(${params}) {\n` +
               guardsBlock +
               letsBlock +
               `    return(list(${returnExpr}))\n` +
               `}\n`;
    },
});

// Per-target facts that registry-wide docs and tests read; field reference
// in emitters/meta.js.
emitter.meta = {
    displayName: "R",
    kind: "executable",
    testTarget: "R",
    ci: { workflow: "test-r.yml", badge: "R" },
    toolchain: {
        probes: [{ candidates: ["Rscript"], args: ["--version"] }],
        docs: {
            minimum: "base R (no packages)",
            tested: "4.5.2 (exact, `r-lib/actions/setup-r`)",
            notes: "",
        },
    },
    guards: "!is.numeric(arr)",
    division: "(x / y)",
    cmp: { eq: "isTRUE(x == 5)", ne: "!isTRUE(x == 5)", forbidNe: "!=" },
    roundTies: "even",
    selectShortCircuits: true,
    minMaxNaN: "propagate",
};

emitter.lang = "r";
module.exports = emitter;
